"""Problem 2: flat-output cubic plans, coefficient table, horizon scaling, planned vs executed (odometry)."""
import math

import numpy as np
import matplotlib.pyplot as plt

from common import (C_ACC, C_MEAS, C_PLAN, FINAL_RUN, GEN, KFUPM_DARK, MUTED, STATE_COLOR, load_csv, save,
                    shade_states, style)
from rm_flatness_nav.flatness import (STANDOFF, T_MIN, V_MAX, XDOT0, FlatTrajectory, poly_eval,
                                      solve_flat_polynomial, time_horizon)


def peak_speed(d0, v0=XDOT0):
    tr = FlatTrajectory(d0, xdot0=v0)
    ts = np.linspace(0, tr.T, 4001)
    vs = np.array([poly_eval(tr.alpha_x, s)[1] for s in ts])
    return vs.max(), ts[vs.argmax()], tr


def chase_segments(d):
    """[(i_start, i_end)] index ranges of contiguous CHASING ticks."""
    st = d["state"]
    out, i = [], 0
    while i < len(st):
        if st[i] == "CHASING":
            j = i
            while j + 1 < len(st) and st[j + 1] == "CHASING":
                j += 1
            out.append((i, j))
            i = j + 1
        else:
            i += 1
    return out


def fmt(x):
    """LaTeX scientific notation with 4 significant digits (0 printed as 0)."""
    if x == 0:
        return "$0$"
    m, e = f"{x:.3e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def main():
    style()
    lines = ["## Problem 2: flatness plans"]
    # ---------- coefficient table ----------
    cases = [("final run, 1st chase (cut at 10.45 s)", 1.440), ("final run, chase to the stop", 1.269),
             ("run 011925, last chase", 1.365), ("run 012232, last chase", 1.375),
             ("spec lower bound", 1.5), ("spec upper bound", 1.8)]
    rows = []
    for name, d0 in cases:
        vpk, tpk, tr = peak_speed(d0)
        a = tr.alpha_x
        x_end, xd_end, _ = poly_eval(a, tr.T)
        rows.append(f"{name} & {d0:.3f} & {tr.T:.2f} & " + f"$0$ & ${a[1]:.2f}$ & " + " & ".join(fmt(c) for c in a[2:]) +
                    f" & {vpk:.4f}\\\\")
        lines.append(f"- d0={d0:.3f} ({name}): T={tr.T:.4f} s, alpha_x={np.array2string(a, precision=6)}, "
                     f"x(T)={x_end:.4f} (goal {d0-STANDOFF:.4f}), xdot(T)={xd_end:.2e}, "
                     f"peak v={vpk:.4f} m/s at t={tpk:.2f} s, xddot(0)={2*a[2]:.4f}, "
                     f"xddot(T)={2*a[2]+6*a[3]*tr.T:.4f} m/s^2, alpha_y={tr.alpha_y}")
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "coeff_rows.tex").write_text("% Generated by analysis/plot_flatness.py (solve_flat_polynomial).\n"
                                        + "\n".join(rows) + "\n")
    c = V_MAX / 1.6
    v_an = XDOT0 + (3 * c - 2 * XDOT0) ** 2 / (3 * (2 * c - XDOT0))
    d_floor = STANDOFF + T_MIN * V_MAX / 1.6
    lines.append(f"- Analytic peak with T = 1.6 D / vmax and xdot0 = {XDOT0}: v_pk = {v_an:.4f} m/s "
                 f"({v_an / V_MAX * 100:.1f} % of vmax); rest-to-rest (xdot0 = 0): 1.5/1.6 vmax = "
                 f"{1.5 / 1.6 * V_MAX:.4f} m/s. T = 4 s floor applies for d0 < {d_floor:.2f} m")

    # ---------- figure: profiles and horizon scaling ----------
    fig, axs = plt.subplots(1, 3, figsize=(7.4, 2.45), gridspec_kw={"wspace": 0.38})
    d0s = [0.6, 1.0, 1.269, 1.5, 1.8]
    for col, d0 in zip(C_ACC, d0s):
        tr = FlatTrajectory(d0)
        ts = np.linspace(0, tr.T, 400)
        P = np.array([poly_eval(tr.alpha_x, s) for s in ts])
        lw = 2.0 if d0 == 1.269 else 1.1
        axs[0].plot(ts, P[:, 0], color=col, lw=lw, label=f"$d_0$={d0:g} m")
        axs[1].plot(ts, P[:, 1], color=col, lw=lw)
    axs[0].set_xlabel("t (s)"); axs[0].set_ylabel("x(t) (m)"); axs[0].set_title("planned position")
    axs[0].legend(fontsize=6.3, loc="upper left", handlelength=1.4)
    axs[1].axhline(V_MAX, color=MUTED, ls="--", lw=0.9)
    axs[1].axhline(v_an, color=KFUPM_DARK, ls=":", lw=0.9)
    axs[1].text(0.2, V_MAX + 0.003, "$v_{max}$", fontsize=7, color=MUTED)
    axs[1].text(16.0, v_an + 0.004, f"peak {v_an:.3f} m/s", fontsize=7, color=KFUPM_DARK, ha="right")
    axs[1].set_ylim(0, 0.18)
    axs[1].set_xlabel("t (s)"); axs[1].set_ylabel(r"$v(t)=\dot x(t)$ (m/s)"); axs[1].set_title("planned speed")
    dd = np.linspace(0.25, 2.0, 300)
    pk = np.array([peak_speed(x)[0] for x in dd])
    pk0 = np.array([peak_speed(x, 0.0)[0] for x in dd])
    axs[2].plot(dd, pk, color=C_PLAN, lw=1.6, label=r"$\dot x(0)=0.06$ (used)")
    axs[2].plot(dd, pk0, color=C_ACC[1], lw=1.1, ls="--", label=r"$\dot x(0)=0$")
    axs[2].axhline(V_MAX, color=MUTED, ls="--", lw=0.9)
    axs[2].axvspan(1.5, 1.8, color=STATE_COLOR["CHASING"], alpha=0.10, lw=0)
    axs[2].axvline(d_floor, color=MUTED, lw=0.7, ls=":")
    axs[2].text(d_floor + 0.03, 0.02, "T = 4 s floor\nbelow", fontsize=6.3, color=MUTED)
    axs[2].text(1.52, 0.02, "spec\nrange", fontsize=6.3, color=KFUPM_DARK)
    axs[2].set_ylim(0, 0.18)
    axs[2].set_xlabel("$d_0$ (m)"); axs[2].set_ylabel("peak speed (m/s)"); axs[2].set_title("horizon scaling")
    axs[2].legend(fontsize=6.3, loc="upper left")
    out1 = save(fig, "p2_profiles")

    # ---------- figure: planned vs executed (final run) ----------
    d = load_csv(FINAL_RUN / "motor_voltage_full.csv")
    t = d["t_s"]
    segs = chase_segments(d)
    fig, axs = plt.subplots(1, 2, figsize=(7.4, 2.6), gridspec_kw={"wspace": 0.3})
    for k, (i0, i1) in enumerate(segs):
        d0 = d["tag_d"][i0]
        tr = FlatTrajectory(d0)
        tc = t[i0:i1 + 1] - t[i0]
        xref = np.array([tr.sample(s)[0] for s in tc])
        vref = np.array([tr.sample(s)[2] for s in tc])
        x0, y0 = d["odom_x"][i0], d["odom_y"][i0]
        yaw0 = d["odom_yaw"][i0] + math.pi          # camera side = driver -x
        dx, dy = d["odom_x"][i0:i1 + 1] - x0, d["odom_y"][i0:i1 + 1] - y0
        along = dx * math.cos(yaw0) + dy * math.sin(yaw0)
        cross = -dx * math.sin(yaw0) + dy * math.cos(yaw0)
        lab = k == len(segs) - 1
        axs[0].plot(t[i0:i1 + 1], xref, color=C_PLAN, lw=1.8, label="plan $x(t)$" if lab else None)
        axs[0].plot(t[i0:i1 + 1], along, color=C_MEAS, lw=1.2, ls="-",
                    label="odometry, along the start heading" if lab else None)
        axs[1].plot(t[i0:i1 + 1], vref, color=C_PLAN, lw=1.8, label=r"plan $\dot x(t)$" if lab else None)
        axs[1].plot(t[i0:i1 + 1], d["v_cmd"][i0:i1 + 1], color=KFUPM_DARK, lw=0.9, ls="--",
                    label="commanded $v$" if lab else None)
        # odometry speed: /odom arrives at ~10 Hz and is repeated between updates; difference new samples only
        ox, oy = d["odom_x"][i0:i1 + 1], d["odom_y"][i0:i1 + 1]
        new = np.r_[True, (np.diff(ox) != 0) | (np.diff(oy) != 0)]
        tn, xn, yn = t[i0:i1 + 1][new], ox[new], oy[new]
        w = 5   # difference over 5 /odom updates (about 0.5 s): single updates jitter over Wi-Fi
        if len(tn) > w:
            sp = np.hypot(xn[w:] - xn[:-w], yn[w:] - yn[:-w]) / (tn[w:] - tn[:-w])
            axs[1].plot(0.5 * (tn[w:] + tn[:-w]), sp, color=C_MEAS, lw=1.1, alpha=0.9,
                        label="odometry speed (0.5 s difference)" if lab else None)
        tf = t[i1]
        lines.append(f"- chase {k+1}: t={t[i0]:.2f}-{tf:.2f} s, d0={d0:.3f} m, T={tr.T:.3f} s, goal "
                     f"{tr.x_goal:.3f} m; plan x at end {xref[-1]:.4f} m, odometry along {along[-1]:.4f} m, "
                     f"cross {cross[-1]*100:+.1f} cm, straight distance {math.hypot(dx[-1], dy[-1]):.4f} m")
        if k == len(segs) - 1:
            err = along - xref
            lines.append(f"  final chase tracking: along - plan: mean {err.mean()*100:+.1f} cm, "
                         f"max |err| {np.abs(err).max()*100:.1f} cm; |cross| max {np.abs(cross).max()*100:.1f} cm")
    for ax in axs:
        shade_states(ax, t, d["state"], alpha=0.10)
        ax.set_xlim(8.0, 25.4)
        ax.set_xlabel("mission time t (s)")
    axs[0].set_ylabel("distance from chase start (m)")
    axs[0].set_title("position: plan vs odometry")
    axs[1].set_ylabel("speed (m/s)")
    axs[1].set_title("speed: plan, command, odometry")
    axs[1].set_ylim(0, 0.2)
    axs[0].legend(loc="upper left", fontsize=6.5)
    axs[1].legend(loc="upper right", fontsize=6.5)
    out2 = save(fig, "p2_plan_vs_odom")
    return [out1, out2], "\n".join(lines)


if __name__ == "__main__":
    outs, txt = main()
    print(txt)
