"""Problem 3: v(t) and V1(t) plot, all four voltages, Table 1 (verbatim rows of motor_voltage_log.csv)."""
import numpy as np
import matplotlib.pyplot as plt

from common import (FINAL_RUN, GEN, KFUPM_DARK, MUTED, STATE_COLOR, WHEEL_COLOR, WHEEL_NAME, load_csv,
                    load_raw_rows, save, shade_states, state_legend_handles, state_segments, style)
from rm_flatness_nav.voltage import K_A, K_V, L_C, R_WHEEL  # package module (eq. 4, 5)


def table1_tex():
    """Write Table 1 rows exactly as they appear in the CSV (no rounding, no edits)."""
    rows = load_raw_rows(FINAL_RUN / "motor_voltage_log.csv")
    head, body = rows[0], rows[1:]
    idx = {k: i for i, k in enumerate(head)}
    lines = []
    for r in body:
        st = r[idx["state"]]
        cells = [r[idx["t_s"]], r[idx["V1"]], r[idx["V2"]], r[idx["V3"]], r[idx["V4"]],
                 r[idx["v_cmd"]], r[idx["w_cmd"]],
                 r[idx["tag_d"]] if r[idx["tag_d"]] else "n/a"]
        cells = [f"${c}$" if c.startswith("-") and c != "n/a" else c for c in cells]
        lines.append(" & ".join(cells) + f" & \\stbadge{{{st}}}\\\\")
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "table1_rows.tex").write_text(
        "% Generated by analysis/plot_voltage.py from data/runs/20261026_015001/motor_voltage_log.csv.\n"
        "% Values copied verbatim (strings), do not edit by hand.\n" + "\n".join(lines) + "\n")
    return len(body)


def main():
    style()
    d = load_csv(FINAL_RUN / "motor_voltage_full.csv")
    lg = load_csv(FINAL_RUN / "motor_voltage_log.csv")
    t, st = d["t_s"], d["state"]
    V = np.vstack([d["V1"], d["V2"], d["V3"], d["V4"]])
    v, w = d["v_cmd"], d["w_cmd"]
    n_rows = table1_tex()

    # ---------- Figure: v(t) and V1(t) (required deliverable) ----------
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(7.2, 4.6), sharex=True, gridspec_kw={"hspace": 0.12})
    for ax in (a1, a2):
        shade_states(ax, t, st)
    shade_states(a1, t, st, alpha=0, labels=True)
    a1.plot(t, v, color=KFUPM_DARK, lw=1.6, label=r"forward speed $v(t)$ (commanded, 20 Hz)")
    a1.axhline(0.16, color=MUTED, ls="--", lw=0.9)
    a1.text(25.0, 0.163, r"$v_{max}=0.16$ m/s", fontsize=7, color=MUTED, va="bottom", ha="right")
    k = int(np.nanargmax(v))
    a1.annotate(f"peak {v[k]:.4f} m/s", (t[k], v[k]), xytext=(t[k] - 6.2, v[k] + 0.012), fontsize=7,
                arrowprops=dict(arrowstyle="-", color=MUTED, lw=0.7))
    a1.set_ylabel("v (m/s)")
    a1.set_ylim(-0.01, 0.19)
    a1b = a1.twinx()
    a1b.plot(t, w, color=STATE_COLOR["ALIGNING"], lw=0.9, ls="-", alpha=0.75)
    a1b.set_ylabel(r"$\omega$ (rad/s)", color=STATE_COLOR["ALIGNING"])
    a1b.set_ylim(-0.42, 0.42)
    a1b.spines["right"].set_visible(True)
    a1b.grid(False)
    a1b.tick_params(axis="y", colors=STATE_COLOR["ALIGNING"], labelcolor=STATE_COLOR["ALIGNING"])
    a1.plot([], [], color=STATE_COLOR["ALIGNING"], lw=0.9, label=r"yaw rate $\omega(t)$ (right axis)")
    a1.legend(loc="center left", ncol=1, bbox_to_anchor=(0.005, 0.42), fontsize=7)

    a2.plot(t, V[0], color=WHEEL_COLOR[0], lw=1.2, label=r"$V_1(t)$ FR, every control tick (20 Hz)")
    a2.plot(lg["t_s"], lg["V1"], "o", ms=3.6, mfc="white", mec=KFUPM_DARK, mew=1.1,
            label=r"$V_1$ logged every 1 s (Table 1)")
    a2.axhline(0, color=MUTED, lw=0.7)
    a2.set_ylabel(r"$V_1$ (V)")
    a2.set_xlabel("mission time t (s)")
    a2.set_xlim(t[0] - 0.05, t[-1] + 0.05)
    lo, hi = np.min(V[0]), np.max(V[0])
    a2.set_ylim(lo - 0.25, hi + 0.75)
    offs = [(8, -4), (-44, -6), (-50, 2), (8, -8), (8, 2)]
    for k, i in enumerate(np.where(np.abs(V[0]) > 1.3)[0]):
        a2.annotate(f"{V[0][i]:+.3f} V", (t[i], V[0][i]), xytext=offs[k % len(offs)], textcoords="offset points",
                    fontsize=6.5, color="#444")
    h1, l1 = a2.get_legend_handles_labels()
    a2.legend(h1 + state_legend_handles(), l1 + [h.get_label() for h in state_legend_handles()],
              loc="upper right", ncol=3, fontsize=6.8)
    out1 = save(fig, "p3_v_V1")

    # ---------- Figure: all four voltages ----------
    fig, ax = plt.subplots(figsize=(7.2, 2.7))
    shade_states(ax, t, st, labels=True)
    for i in range(4):
        ax.plot(t, V[i], color=WHEEL_COLOR[i], lw=1.0 if i in (2, 3) else 1.3,
                ls="--" if i in (2, 3) else "-", label=WHEEL_NAME[i])
    ax.axhline(0, color=MUTED, lw=0.7)
    ax.set_xlabel("mission time t (s)")
    ax.set_ylabel("armature voltage (V)")
    ax.set_xlim(t[0] - 0.05, t[-1] + 0.05)
    ax.legend(ncol=4, loc="lower left")
    out2 = save(fig, "p3_voltages_all")

    # ---------- numbers ----------
    dt_ros = np.diff(d["ros_time"])
    segs = state_segments(t, st)
    arrived = st == "ARRIVED"
    lines = ["## Problem 3: voltages (final run 20261026_015001)",
             f"- Constants: r = {R_WHEEL} m, Lc = {L_C} m, Kv = {K_V}, Ka = {K_A}, dt = 0.05 s (20 Hz control)",
             f"- motor_voltage_log.csv rows: {n_rows} (t = {lg['t_s'][0]:.0f} .. {lg['t_s'][-1]:.0f} s)",
             f"- motor_voltage_full.csv ticks: {len(t)}, t = {t[0]:.3f} .. {t[-1]:.3f} s",
             f"- Tick interval from ros_time: mean {dt_ros.mean()*1000:.1f} ms, std {dt_ros.std()*1000:.1f} ms, "
             f"min {dt_ros.min()*1000:.1f} ms, max {dt_ros.max()*1000:.1f} ms",
             "- State segments: " + "; ".join(f"{s} {a:.2f}-{b:.2f} s" for s, a, b in segs),
             f"- Peak commanded v: {np.nanmax(v):.4f} m/s at t = {t[np.nanargmax(v)]:.2f} s",
             f"- V1 range: {V[0].min():.3f} .. {V[0].max():.3f} V; all wheels range {V.min():.3f} .. {V.max():.3f} V",
             f"- ARRIVED ticks: {arrived.sum()}, max |V| while ARRIVED: {np.abs(V[:, arrived]).max():.3f} V "
             f"(first ARRIVED tick t = {t[arrived][0]:.3f} s)",
             f"- Steady search turn: w = 0.30 rad/s -> |w_i| = {0.2*0.3/0.05:.3f} rad/s, |V| = {K_V*1.2:.3f} V; "
             f"start step adds Ka*1.2/0.05 = {K_A*1.2/0.05:.3f} V -> {K_V*1.2 + K_A*1.2/0.05:.3f} V",
             "- Ticks with |V1| > 1.3 V (step changes): " + ", ".join(
                 f"t={t[i]:.2f} {st[i-1] if i else '-'}->{st[i]} V1={V[0][i]:+.3f} V2={V[1][i]:+.3f}"
                 for i in np.where(np.abs(V[0]) > 1.3)[0])]
    # deceleration inside CHASING (Ka term negative)
    ch = st == "CHASING"
    dw = np.diff(np.r_[0.0, d["w1"]]) / 0.05
    neg_ka = ch & (dw < 0)
    lines.append(f"- CHASING ticks with dw1/dt < 0: {neg_ka.sum()}, Ka*dw1/dt min {K_A*dw[neg_ka].min():.3f} V")
    neg_v = (V < -1e-9) & ch
    lines.append(f"- CHASING ticks with any negative V_i: {int(neg_v.any(axis=0).sum())}")
    return [out1, out2], "\n".join(lines)


if __name__ == "__main__":
    outs, txt = main()
    print(txt)
