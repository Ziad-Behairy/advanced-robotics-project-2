"""Final run timeline, top view from odometry, and the table of all logged runs."""
import math

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

from common import (C_MEAS, C_PLAN, DATA, FINAL_RUN, FLOOR_RUNS, GEN, KFUPM_DARK, MUTED, STATE_COLOR, STATES,
                    load_csv, save, shade_states, state_segments, style)
from rm_flatness_nav.flatness import FlatTrajectory

ALL_RUNS = [  # (folder, kind)
    ("dryrun/20261026_010948", "dry run, \\code{cmd_vel} remapped"),
    ("wheels_off_test/20261026_011222", "wheels off the ground"),
    ("wheels_off_test/20261026_011631", "wheels off the ground"),
    ("runs/20261026_011925", "floor run 1"),
    ("runs/20261026_012232", "floor run 2"),
    ("dryrun/20261026_013032", "dry run, \\code{cmd_vel} remapped"),
    ("runs/20261026_015001", "floor run 3 (final, filmed)"),
]


def chase_starts(st):
    return [i for i in range(len(st)) if st[i] == "CHASING" and (i == 0 or st[i - 1] != "CHASING")]


def runs_table():
    rows, lines = [], ["## All logged runs"]
    for folder, kind in ALL_RUNS:
        d = load_csv(DATA / folder / "motor_voltage_full.csv")
        t, st, td = d["t_s"], d["state"], d["tag_d"]
        cs = chase_starts(st)
        run = folder.split("/")[-1]
        arr = np.where(st == "ARRIVED")[0]
        seen = td[~np.isnan(td)]
        if cs and len(arr):
            i0 = cs[-1]
            d0 = td[i0]
            T = FlatTrajectory(d0).T
            dur = t[arr[0]] - t[i0]
            trig = "plan time $T$" if dur >= T - 0.1 else "odometry"
            d0s, Ts, stop = f"{d0:.3f}", f"{T:.2f}", f"{t[arr[0]]:.2f}"
        else:
            d0s = Ts = stop = "n/a"
            trig = "no tag in view (search only)"
        last = f"{seen[-1]:.3f}" if len(seen) else "n/a"
        meas = FLOOR_RUNS.get(run)
        meas_s = f"\\textbf{{{meas*100:.0f}\\,cm}}" if meas is not None else "n/a"
        rows.append(f"\\code{{{run}}} & {kind} & {t[-1]:.1f} & {len(cs)} & {d0s} & {Ts} & {stop} & {trig} & "
                    f"{last} & {meas_s}\\\\")
        lines.append(f"- {folder}: {kind}; {t[-1]:.1f} s; chase starts {len(cs)} at "
                     f"{[round(t[i], 2) for i in cs]}; d0 {d0s}; T {Ts}; ARRIVED {stop}; trigger {trig}; "
                     f"last camera d {last}; tape {meas}")
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "runs_rows.tex").write_text("% Generated by analysis/plot_run.py\n" + "\n".join(rows) + "\n")
    return "\n".join(lines)


def main():
    style()
    d = load_csv(FINAL_RUN / "motor_voltage_full.csv")
    t, st = d["t_s"], d["state"]
    lines = [runs_table(), "## Final run timeline"]

    # ---------- timeline ----------
    fig, axs = plt.subplots(4, 1, figsize=(7.3, 5.6), sharex=True,
                            gridspec_kw={"height_ratios": [0.42, 1, 1, 1], "hspace": 0.13})
    a0 = axs[0]
    for s, a, b in state_segments(t, st):
        a0.axvspan(a, b, color=STATE_COLOR[s], alpha=0.85, lw=0)
        if b - a > 2.0:
            a0.text((a + b) / 2, 0.5, s, ha="center", va="center", color="white", fontsize=6.6,
                    fontweight="bold", transform=a0.get_xaxis_transform())
    a0.set_yticks([]); a0.grid(False)
    a0.set_title("final run 20261026_015001: state machine, sensing and motion", loc="left")
    for s in ("left", "bottom"):
        a0.spines[s].set_visible(False)

    ax = axs[1]
    shade_states(ax, t, st)
    seen = ~np.isnan(d["tag_d"])
    # tag_d holds the LAST detection; mark only the ticks where a new value arrived
    new = seen & np.r_[True, np.diff(np.nan_to_num(d["tag_d"])) != 0]
    ax.plot(t[seen], d["tag_d"][seen], color=KFUPM_DARK, lw=0.8, alpha=0.5, drawstyle="steps-post")
    ax.plot(t[new], d["tag_d"][new], ".", ms=3.5, color=KFUPM_DARK, label="camera distance $d$ (new value)")
    ax.plot(t, d["tof"], color=STATE_COLOR["SEARCHING"], lw=0.9, label="front ToF range")
    ax.axhline(0.20, color=C_MEAS, ls="--", lw=0.9)
    ax.text(0.2, 0.215, "brake threshold 0.20 m", fontsize=6.5, color=C_MEAS)
    ax.set_ylabel("range (m)"); ax.set_ylim(0, 1.95)
    ax.legend(loc="upper right", fontsize=6.6, ncol=2)

    ax = axs[2]
    shade_states(ax, t, st)
    b = d["tag_bearing"].copy()
    b[~seen] = np.nan
    ax.plot(t[new], np.degrees(b[new]), ".", ms=3.5, color=STATE_COLOR["ALIGNING"], label="tag bearing")
    ax.axhspan(-np.degrees(0.18), np.degrees(0.18), color=STATE_COLOR["CHASING"], alpha=0.12, lw=0)
    ax.text(0.2, 11.5, r"$|\theta|\leq 0.18$ rad (10.3$^\circ$)", fontsize=6.5, color=KFUPM_DARK)
    ax.plot(t, np.degrees(d["w_cmd"]), color=MUTED, lw=0.9, label=r"commanded $\omega$ (deg/s)")
    ax.set_ylabel("deg  |  deg/s"); ax.set_ylim(-35, 55)
    ax.legend(loc="upper right", fontsize=6.6, ncol=2)

    ax = axs[3]
    shade_states(ax, t, st)
    yaw = np.unwrap(d["odom_yaw"])
    ax.plot(t, np.degrees(yaw - yaw[0]), color=C_PLAN, lw=1.2, label="odometry heading change")
    x0, y0 = d["odom_x"][0], d["odom_y"][0]
    ax.set_ylabel("heading (deg)")
    axb = ax.twinx()
    axb.plot(t, np.hypot(d["odom_x"] - x0, d["odom_y"] - y0), color=C_MEAS, lw=1.2)
    axb.set_ylabel("displacement (m)", color=C_MEAS)
    axb.tick_params(axis="y", colors=C_MEAS, labelcolor=C_MEAS)
    axb.spines["right"].set_visible(True); axb.grid(False)
    ax.plot([], [], color=C_MEAS, label="odometry displacement from start (right)")
    ax.legend(loc="center right", fontsize=6.6)
    ax.set_xlabel("mission time t (s)")
    ax.set_xlim(t[0] - 0.05, t[-1] + 0.05)
    out1 = save(fig, "p5_timeline")

    first_seen = t[seen][0]
    lines += [f"- first detection at t = {first_seen:.2f} s, bearing {d['tag_bearing'][seen][0]:.3f} rad, d {d['tag_d'][seen][0]:.3f} m",
              f"- heading change before first detection: {np.degrees(yaw[seen.argmax()] - yaw[0]):.1f} deg",
              f"- heading change at first CHASING tick: {np.degrees(yaw[chase_starts(st)[0]] - yaw[0]):.1f} deg",
              f"- ToF range over the run: {np.nanmin(d['tof']):.3f} .. {np.nanmax(d['tof']):.3f} m",
              f"- last camera d: {d['tag_d'][seen][-1]:.3f} m; last new detection at t = {t[new][-1]:.2f} s",
              f"- odometry displacement start->end: {math.hypot(d['odom_x'][-1]-x0, d['odom_y'][-1]-y0):.4f} m; "
              f"path length {np.sum(np.hypot(np.diff(d['odom_x']), np.diff(d['odom_y']))):.4f} m"]

    # ---------- top view ----------
    fig, ax = plt.subplots(figsize=(7.2, 2.5))
    # rotate odometry so the final chase heads along +X (camera side = driver -x)
    i2 = chase_starts(st)[-1]
    yaw2 = d["odom_yaw"][i2] + math.pi
    c, s = math.cos(-yaw2), math.sin(-yaw2)
    X = c * (d["odom_x"] - d["odom_x"][i2]) - s * (d["odom_y"] - d["odom_y"][i2])
    Y = s * (d["odom_x"] - d["odom_x"][i2]) + c * (d["odom_y"] - d["odom_y"][i2])
    H = d["odom_yaw"] + math.pi - yaw2
    for seg, a, bb in state_segments(t, st):
        m = (t >= a) & (t <= bb + 1e-9)
        ax.plot(X[m], Y[m], color=STATE_COLOR[seg], lw=2.4, solid_capstyle="round")
    d0 = d["tag_d"][i2]
    tr = FlatTrajectory(d0)
    ax.plot([0, tr.x_goal], [0, 0], color=C_PLAN, ls=":", lw=1.2)
    # tag position as estimated at the chase start: straight ahead along the bearing, d0 from the front
    th = d["tag_bearing"][i2]
    ax.annotate("", xy=(0.25 * math.cos(th), 0.25 * math.sin(th)), xytext=(0, 0),
                arrowprops=dict(arrowstyle="->", color=STATE_COLOR["ALIGNING"], lw=1.0))
    for i in range(0, len(t), 20):
        ax.annotate("", xy=(X[i] + 0.07 * math.cos(H[i]), Y[i] + 0.07 * math.sin(H[i])), xytext=(X[i], Y[i]),
                    arrowprops=dict(arrowstyle="-|>", color="#333", lw=0.6, mutation_scale=6))
    ax.plot(X[0], Y[0], "o", color=STATE_COLOR["SEARCHING"], ms=6)
    ax.plot(X[-1], Y[-1], "s", color=STATE_COLOR["ARRIVED"], ms=6)
    ax.text(X[0] - 0.02, Y[0] + 0.06, "start (rotates in place)", fontsize=7, ha="center")
    ax.text(X[-1], Y[-1] - 0.07, "stop: 20 cm from T3 (tape)", fontsize=7, ha="center", va="top")
    ax.text(0.30, 0.03, "planned straight path $y(t)=0$, length $d_0-0.20=$" + f"{tr.x_goal:.3f} m",
            fontsize=6.5, color=C_PLAN)
    ax.text(0.10, -0.2, f"tag bearing at chase start ({math.degrees(th):.1f}$^\\circ$)",
            fontsize=6.5, color=STATE_COLOR["ALIGNING"])
    ax.set_xlim(-0.4, 1.3); ax.set_ylim(-0.32, 0.2)
    ax.set_aspect("equal")
    ax.set_xlabel("X along the final chase heading (m)")
    ax.set_ylabel("Y left (m)")
    handles = [Line2D([], [], color=STATE_COLOR[s], lw=2.4, label=s) for s in STATES]
    handles.append(Line2D([], [], color="#333", lw=0.6, marker=">", ms=4, label="camera heading (1 s)"))
    ax.legend(handles=handles, fontsize=6.5, loc="upper left", bbox_to_anchor=(1.01, 1.0))
    ax.set_title("top view from /odom (robot center)", loc="left")
    out2 = save(fig, "p5_topview")
    lines.append(f"- final chase start bearing {th:.3f} rad ({math.degrees(th):.1f} deg); end point in chase frame "
                 f"X={X[-1]:.3f} Y={Y[-1]:.3f} m; heading change during final chase {math.degrees(H[-1]):.1f} deg")
    return [out1, out2], "\n".join(lines)


if __name__ == "__main__":
    outs, txt = main()
    print(txt)
